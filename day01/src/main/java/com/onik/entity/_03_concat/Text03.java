package com.onik.entity._03_concat;

public class Text03 {
    public static void main(String[] args) {
        System.out.println(50 + 10);
        System.out.println(50 + "10");
        System.out.println(50 + 50 + "10"+ 10 + 1);
        System.out.println('a' + 0);
        System.out.println('a' + 10);
        System.out.println('a' + 'a');
        System.out.println('a' + "10");
    }
}
